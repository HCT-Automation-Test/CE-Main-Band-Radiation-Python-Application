def test_lte_channel_table_matches_all_138_final_rows() -> None:
    assert len(EXPECTED_CHANNEL_ROWS) == 46
    checked_rows = 0

    for (
        band,
        bandwidth,
        dl_channel_values,
        dl_frequency_values,
        ul_channel_values,
        ul_frequency_values,
    ) in EXPECTED_CHANNEL_ROWS:
        for index, test_channel in enumerate(ChannelEnum):
            assert (
                resolve_arfcn(band, bandwidth, test_channel)
                == ul_channel_values[index]
            )
            assert (
                resolve_lte_frequency_mhz(band, bandwidth, test_channel)
                == ul_frequency_values[index]
            )
            assert (
                resolve_dl_channel(band, bandwidth, test_channel)
                == dl_channel_values[index]
            )
            assert (
                resolve_dl_frequency_mhz(band, bandwidth, test_channel)
                == dl_frequency_values[index]
            )
            checked_rows += 1

    assert checked_rows == 138


def test_lte_channel_lookup_rejects_missing_combination() -> None:
    with pytest.raises(
        ValueError,
        match=r"band='B34'.*bandwidth='20'.*test_channel='mid'",
    ):
        resolve_arfcn(LTEBand.B34, 20.0, ChannelEnum.MID)
